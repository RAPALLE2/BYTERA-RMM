let gridEl = null;
let headerEl = null;
function buildChrome(root) {
  const panel = root.querySelector(".start-menu-panel");
  const header = panel.querySelector(".start-menu-header");
  headerEl = header;
  header.innerHTML = `
    <span>Applications</span>
    <span class="sm-tools">
      <button class="sm-newfolder-btn" title="Create a new folder" style="display:none">+ Folder</button>
      <button class="sm-catreset-btn" title="Sort all apps back into the default folders (categories)" style="display:none">Sort by categories</button>
      <button class="sm-done-btn" title="Finish editing" style="display:none">Finish editing</button>
    </span>`;
  header.style.cssText = "display:flex;align-items:center;justify-content:space-between;gap:8px";

  // "Finish editing" ends the GLOBAL layout edit mode (same switch as
  // dashboard/profile) so everything stays in sync.
  header.querySelector(".sm-done-btn").addEventListener("click", async () => {
    const { setDashEdit } = await import("./persist.js");
    setDashEdit(false);
    try { window.dispatchEvent(new CustomEvent("dashedit-changed")); } catch {}
  });
  header.querySelector(".sm-catreset-btn").addEventListener("click", async () => {
    const ok = await uiConfirm("Sort all apps back into the default folders? Your own folders are dissolved in the process.",
      { okText: "Re-sort" });
    if (ok) resetToCategories();
  });
  header.querySelector(".sm-newfolder-btn").addEventListener("click", async () => {
    const name = await uiPrompt("Create a new folder", {
      placeholder: "New folder", okText: "Create",
    });
    if (name == null) return;
    layout.items.push({ t: "folder", id: `f_${Math.random().toString(36).slice(2, 8)}`,
                        name: name.trim() || "New folder", open: false, apps: [] });
    save(); render();
  });

  // Replace the old static grid with our dynamic container,
  // the original buttons stay as a hidden catalog.
  const oldGrid = panel.querySelector(".start-menu-grid");
  oldGrid.style.display = "none";
  oldGrid.classList.add("sm-catalog-hidden");
  gridEl = document.createElement("div");
  gridEl.className = "start-menu-grid sm-live-grid";
  oldGrid.after(gridEl);
}

// Set header buttons + panel class according to the current editMode.
function applyEditChrome() {
  if (headerEl) {
    headerEl.querySelector(".sm-newfolder-btn").style.display = editMode ? "" : "none";
    headerEl.querySelector(".sm-catreset-btn").style.display = editMode ? "" : "none";
    headerEl.querySelector(".sm-done-btn").style.display = editMode ? "" : "none";
  }
  const panel = gridEl && gridEl.closest(".start-menu-panel");
  if (panel) panel.classList.toggle("sm-editing", editMode);
}

