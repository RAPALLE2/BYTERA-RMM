// startmenu.js
// ------------
// Customizable application menu: free arrangement via drag & drop, folders
// (create / rename / open / close / delete), drag apps into folders
// and back out. The layout is stored per user in localStorage.
// The actual app catalog (which apps exist, icon, label, open behavior)
// stays in index.html/app.js - this module only manages the ARRANGEMENT
// and calls the existing opener on click.
//
// Layout-Modell (localStorage "rmm_appmenu:<user>"):
//   { items: [ {t:"app", id:"scripts"} | {t:"folder", id:"f_ab12",
//               name:"Maintenance", open:false, apps:["scripts","bulk"]} ] }
// Apps newly added to the catalog that are not placed anywhere yet are
// automatically appended at the end. Apps that no longer exist drop out.

import { uiPrompt, uiConfirm } from "./utils.js";
import { getDashEdit } from "./persist.js";
import { t } from "./i18n.js";
import { CATEGORIES, categoryOf, categoryInfo } from "./appcategories.js";

let CATALOG = {};          // id -> { id, icon, label }
let CATALOG_ORDER = [];    // order from the DOM (for new apps)
let layout = { items: [] };
let userKey = "rmm_appmenu:default";
let openApp = () => {};    // callback: (appId) => void  (from app.js)
let isAllowed = () => true;// callback: (appId) => bool  (permission gate)
let editMode = false;

// -------------------------------------------------------------
// Persistence
// -------------------------------------------------------------
function load() {
  try {
    const raw = localStorage.getItem(userKey);
    if (raw) layout = JSON.parse(raw);
  } catch { /* corrupt -> default */ }
  if (!layout || !Array.isArray(layout.items)) layout = { items: [] };
}
function save() {
  try {
    localStorage.setItem(userKey, JSON.stringify(layout));
    // Also persist the start-menu layout on the server.
    import("./persist.js").then((m) => m.syncToServerSoon()).catch(() => {});
  } catch {}
}

// Read the catalog from the (hidden) DOM buttons in index.html.
function readCatalog(rootEl) {
  CATALOG = {}; CATALOG_ORDER = [];
  rootEl.querySelectorAll("[data-app]").forEach((btn) => {
    const id = btn.dataset.app;
    // ":scope >" = only DIRECT child spans. Without it the selector, after
    // the emoji->SVG replacement (icons.js), hits the .svgicon span INSIDE .app-icon and
    // returns empty label text -> gray, empty tiles.
    const iconEl = btn.querySelector(":scope > .app-icon");
    const labelEl = btn.querySelector(":scope > span:not(.app-icon)");
    CATALOG[id] = {
      id,
      // innerHTML instead of textContent: this takes over both an emoji and a
      // <span class="svgicon"> generated by icons.js correctly.
      icon: iconEl ? iconEl.innerHTML : "",
      iconText: iconEl ? iconEl.textContent.trim() : "",
      label: labelEl ? labelEl.textContent.trim() : id,
    };
    CATALOG_ORDER.push(id);
  });
}

// Reconcile the layout with the catalog: append missing apps, remove dead ones.
// While the modules are not loaded yet, the catalog does not know their apps.
// Then reconcile() must NOT delete references to unknown apps as "dead" -
// otherwise the arrangement (folders, order) of module apps would be lost on
// every page load. app.js unlocks after loadModules().
let pruneLocked = true;
export function unlockCatalogPruning() { pruneLocked = false; reconcile(); render(); }

function reconcile() {
  const placed = new Set();
  const walk = (arr) => arr.forEach((it) => {
    if (it.t === "app") placed.add(it.id);
    else if (it.t === "folder") (it.apps || []).forEach((a) => placed.add(a));
  });
  walk(layout.items);

  // Remove dead app references
  layout.items = layout.items.filter((it) => {
    if (it.t === "app") return pruneLocked || !!CATALOG[it.id];
    if (it.t === "folder") { if (!pruneLocked) it.apps = (it.apps || []).filter((a) => CATALOG[a]); return true; }
    return false;
  });

  // Default folders: once (new users AND existing layouts) sort all loose
  // apps into folders by category - only once the module apps are known
  // too. The users' own folders stay as they are.
  if (!layout.grouped && !pruneLocked) { groupLooseApps(placed); layout.grouped = true; }

  // New apps (in the catalog but placed nowhere): with a grouped layout into
  // the matching category folder, otherwise append at the end.
  for (const id of CATALOG_ORDER) {
    if (placed.has(id) || !CATALOG[id]) continue;
    placed.add(id);
    if (layout.grouped) categoryFolder(categoryOf(id)).apps.push(id);
    else layout.items.push({ t: "app", id });
  }
  save();
}

// Get or create a category folder (at the end, in category order).
function categoryFolder(key) {
  let f = layout.items.find((x) => x.t === "folder" && x.cat === key);
  if (!f) {
    const info = categoryInfo(key);
    f = { t: "folder", id: `cat_${key}`, cat: key, name: info.name, open: false, apps: [] };
    layout.items.push(f);
  }
  return f;
}

// Move all apps that sit directly in the menu into their category folders.
function groupLooseApps() {
  const loose = layout.items.filter((it) => it.t === "app").map((it) => it.id);
  if (!loose.length) return;
  layout.items = layout.items.filter((it) => it.t !== "app");
  // reassign free slots: own folders first (old order), then categories
  layout.items.sort((a, b) => (a.pos ?? 0) - (b.pos ?? 0)).forEach((it) => { delete it.pos; });
  const byCat = new Map();
  for (const id of loose) {
    const k = categoryOf(id);
    if (!byCat.has(k)) byCat.set(k, []);
    byCat.get(k).push(id);
  }
  for (const c of CATEGORIES) {
    const ids = byCat.get(c.key);
    if (ids) categoryFolder(c.key).apps.push(...ids.filter((id) => !categoryFolder(c.key).apps.includes(id)));
  }
}

/** Order the whole start menu by the default categories (button in
 *  edit mode). Apps from the user's own folders move back too. */
export function resetToCategories() {
  const all = [];
  for (const it of layout.items) {
    if (it.t === "app") all.push(it.id);
    else if (it.t === "folder") all.push(...(it.apps || []));
  }
  layout = { items: all.map((id) => ({ t: "app", id })), grouped: false };
  groupLooseApps();
  layout.grouped = true;
  reconcile();
  render();
}

// -------------------------------------------------------------
// Public init
// -------------------------------------------------------------
export function initStartMenu({ root, username, onOpenApp, allowed }) {
  userKey = `rmm_appmenu:${username || "default"}`;
  openApp = onOpenApp || openApp;
  isAllowed = allowed || isAllowed;
  readCatalog(root);
  load();
  reconcile();
  buildChrome(root);
  // Edit mode is tied to the same global "edit layout" switch
  // as the dashboard (profile checkbox / "finish editing").
  // No separate menu button anymore.
  editMode = !!getDashEdit();
  window.addEventListener("dashedit-changed", () => {
    editMode = !!getDashEdit();
    applyEditChrome();
    render();
  });
  applyEditChrome();
  render();
}

// Called by app.js after loading permissions (hides apps without a
// permission, without changing the layout).
export function refreshStartMenu() { render(); }

// Set the user AFTER the fact.
//
// Why this is needed: initStartMenu() runs from initMenusAndButtons(),
// so BEFORE login is through - state.user is still null then. The layout
// therefore always landed under "rmm_appmenu:default" instead of the user.
// That key was deliberately ignored by the server sync (persist.js)
// because it belongs to no user. Result: folders and arrangement in the start
// menu lived ONLY in the browser and were gone under a different URL.
//
// This function is called after login (and after hydrateFromServer):
// it switches to the real user key, adopts an existing "default" layout
// once, and redraws.
export function setStartMenuUser(username) {
  const nextKey = `rmm_appmenu:${username || "default"}`;
  if (nextKey === userKey) return;
  const legacyKey = userKey;                 // usually "rmm_appmenu:default"
  userKey = nextKey;
  load();
  // Nothing stored under the user yet? Then adopt the old, browser-local
  // layout once so nobody loses their folders.
  const empty = !layout || !Array.isArray(layout.items) || !layout.items.length;
  if (empty) {
    try {
      const raw = localStorage.getItem(legacyKey);
      if (raw) {
        const old = JSON.parse(raw);
        if (old && Array.isArray(old.items) && old.items.length) layout = old;
      }
    } catch {}
  }
  // The default key is no longer needed and would only get in the way for the
  // next user on the same browser.
  try { if (legacyKey.endsWith(":default")) localStorage.removeItem(legacyKey); } catch {}
  reconcile();   // saves under the new key + triggers the server sync
  render();
}

// Dynamic catalog entries (e.g. saved web apps from the internal browser):
// add an app to the start menu at runtime or remove it.
export function addCatalogEntry(id, icon, label) {
  const existed = !!CATALOG[id];
  CATALOG[id] = { id, icon: icon || "🌐", iconText: icon || "🌐", label: label || id };
  if (!existed) CATALOG_ORDER.push(id);
  reconcile();   // automatically appends new apps to the layout
  save();
  render();
}
export function removeCatalogEntry(id) {
  if (!CATALOG[id]) return;
  delete CATALOG[id];
  CATALOG_ORDER = CATALOG_ORDER.filter((x) => x !== id);
  reconcile();   // removes dead references from the layout
  save();
  render();
}

